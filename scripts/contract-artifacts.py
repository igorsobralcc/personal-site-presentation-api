"""Generate deterministic YAML and a dependency-free C# HTTP client from OpenAPI JSON."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def yaml_lines(value, indent=0):
    prefix = " " * indent
    if isinstance(value, dict) and value:
        for key, child in value.items():
            key_text = json.dumps(key) if key.startswith(("#", "/")) or key.isdigit() else key
            if isinstance(child, (dict, list)) and child:
                yield prefix + key_text + ":"
                yield from yaml_lines(child, indent + 2)
            else:
                yield prefix + key_text + ": " + json.dumps(child, ensure_ascii=False)
    elif isinstance(value, list) and value:
        for child in value:
            if isinstance(child, (dict, list)) and child:
                yield prefix + "-"
                yield from yaml_lines(child, indent + 2)
            else:
                yield prefix + "- " + json.dumps(child, ensure_ascii=False)


def artifacts(document):
    yaml = "# Generated from docs/openapi.json by scripts/contract-artifacts.py.\n"
    yaml += "\n".join(yaml_lines(document)) + "\n"
    lines = [
        "// <auto-generated />", "#nullable enable", "using System.Net.Http.Json;", "using System.Text.Json;", "",
        "namespace PersonalSite.Presentation.Client;", "",
        "public sealed class PresentationClient(HttpClient client)", "{"
    ]
    for path, item in document["paths"].items():
        for method, operation in item.items():
            if method not in {"get", "put", "post", "patch", "delete"}:
                continue
            operation_name = operation["operationId"]
            operation_name = operation_name[0].upper() + operation_name[1:] + "Async"
            args = []
            if "{id}" in path:
                args.append("Guid id")
            if "requestBody" in operation:
                args.append("JsonElement body")
            args.extend(["string? ifMatch = null", "string? ifNoneMatch = null", "CancellationToken cancellationToken = default"])
            lines.extend([
                f"    public async Task<HttpResponseMessage> {operation_name}({', '.join(args)})", "    {",
                f'        using var request = new HttpRequestMessage(new HttpMethod("{method.upper()}"), $"{path}");'
            ])
            if "requestBody" in operation:
                media_type = next(iter(operation["requestBody"]["content"]))
                lines.extend([
                    "        request.Content = JsonContent.Create(body);",
                    f'        request.Content.Headers.ContentType = new System.Net.Http.Headers.MediaTypeHeaderValue("{media_type}");'
                ])
            lines.extend([
                '        if (ifMatch is not null) { request.Headers.TryAddWithoutValidation("If-Match", ifMatch); }',
                '        if (ifNoneMatch is not null) { request.Headers.TryAddWithoutValidation("If-None-Match", ifNoneMatch); }',
                "        return await client.SendAsync(request, cancellationToken);", "    }", ""
            ])
    lines.extend(["}", ""])
    return {ROOT / "docs/openapi.yaml": yaml, ROOT / "clients/PresentationClient.generated.cs": "\n".join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = json.loads((ROOT / "docs/openapi.json").read_text(encoding="utf-8"))
    for path, content in artifacts(document).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated contract artifact is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print("Contract YAML and C# client are current." if args.check else "Generated contract YAML and C# client.")


if __name__ == "__main__":
    main()
